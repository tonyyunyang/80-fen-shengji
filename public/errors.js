export function errorText(message) {
  if (locale !== 'en' || !message) return message;
  if (EN[message]) return EN[message];
  const follow = /^请跟出 (\d+) 张牌$/.exec(message);
  if (follow) return 'Follow with exactly ' + follow[1] + (follow[1] === '1' ? ' card.' : ' cards.');
  const models = /^读取模型列表失败（HTTP (\d+)），可以稍后重试或手动填写$/.exec(message);
  if (models) return 'Model lookup failed (HTTP '+models[1]+'). Try later or enter model IDs manually.';
  if (/^STALE_BID:/.test(message)) return 'The bidding context changed. Use the current choices.';
  if (/^SUPERSEDED_BID:/.test(message)) return 'Another bid superseded this one.';
  return message.replace('：请检查服务端配置或稍后重试', ': check the connection settings or try again later.');
}
