const cache=new Map();
export function cardGlyph(value){
  if(cache.has(value))return cache.get(value);
  const rows=value==='10'?pixels['1'].map((row,y)=>row+'0'+pixels['0'][y]):pixels[value];
  if(!rows)return '';
  let path='';
  rows.forEach((row,y)=>{for(let x=0;x<row.length;){if(row[x]!=='1'){x++;continue;}let end=x+1;while(row[end]==='1')end++;path+=`M${x} ${y}h${end-x}v1h-${end-x}z`;x=end;}});
  const result=`<svg viewBox="0 0 ${rows[0].length} ${rows.length}" aria-hidden="true" focusable="false" shape-rendering="crispEdges"><path fill="currentColor" d="${path}"/></svg>`;
  cache.set(value,result);return result;
}
