import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

// Keep the approved bitmap byte-for-byte. Composite its existing ink treatment
// with the card paper inside one SVG image, before CSS transforms/3D layers.
// This avoids relying on a browser's cross-layer mix-blend-mode implementation.
const directory = new URL('../public/assets/cards/', import.meta.url);
const atlas = await readFile(new URL('pixel-court.webp', directory));
const hash = createHash('sha256').update(atlas).digest('hex');
const rgb = (slope, intercept = 0) => ['R', 'G', 'B'].map(channel =>
  `      <feFunc${channel} type="linear" slope="${slope}" intercept="${intercept}"/>`).join('\n');
// CSS background-position indexes a uniform 4x4 grid. The SVG must fill its
// background box without introducing a second, letterboxed coordinate system.
// The renderer gives each individual illustration its natural 2:3 frame.
const svg = `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="1024" height="1536" viewBox="0 0 1024 1536" preserveAspectRatio="none">
  <!-- Generated by scripts/build-card-paper.mjs. Original atlas SHA-256: ${hash} -->
  <defs>
    <filter id="paper" x="0" y="0" width="100%" height="100%" color-interpolation-filters="sRGB">
      <feComponentTransfer>
${rgb(1.14, -.07)}
      </feComponentTransfer>
      <feComponentTransfer result="ink">
${rgb(1.1)}
      </feComponentTransfer>
      <feFlood flood-color="#f2eddf" result="stock"/>
      <feBlend in="ink" in2="stock" mode="multiply"/>
    </filter>
  </defs>
  <image width="1024" height="1536" image-rendering="pixelated" filter="url(#paper)" xlink:href="data:image/webp;base64,${atlas.toString('base64')}"/>
</svg>
`;
await writeFile(new URL('pixel-court-paper.svg', directory), svg);
console.log('Generated paper-composited court/joker atlas; original bitmap unchanged.');
